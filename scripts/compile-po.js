// Compiles locales/*.po into src/locales/translations.ts (generated, not committed).
const fs = require('fs');
const path = require('path');
const { poToCatalog } = require('./poParser.js');

const rootDir = path.resolve(__dirname, '..');
const localesDir = path.join(rootDir, 'locales');
const outDir = path.join(rootDir, 'src', 'locales');
const outFile = path.join(outDir, 'translations.ts');

const translations = {};
for (const file of fs.readdirSync(localesDir).sort()) {
  if (file.endsWith('.po')) {
    const locale = path.basename(file, '.po');
    translations[locale] = poToCatalog(fs.readFileSync(path.join(localesDir, file), 'utf8'));
  }
}

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  outFile,
  '// Generated by scripts/compile-po.js from locales/*.po. Do not edit.\n'
  + `const translations: Record<string, Record<string, string>> = ${JSON.stringify(translations, null, 2)};\n\n`
  + 'export default translations;\n',
  'utf8',
);

const summary = Object.keys(translations).map((k) => `${k}(${Object.keys(translations[k]).length})`).join(' ');
console.info(`compile-po: ${summary}`);
